"use client";

import { useEffect, useRef, useState } from "react";
import { Loader2 } from "lucide-react";
import { createClient } from "@/lib/supabase/client";
import { Button } from "@/components/ui/button";
import { Label } from "@/components/ui/label";

type Mode =
  | { kind: "loading" }
  | { kind: "enroll"; factorId: string; qrCode: string; secret: string }
  | { kind: "verify"; factorId: string }
  | { kind: "error"; message: string };

/**
 * Second sign-in step, shown on /login right after the password and on /mfa
 * (where the proxy sends every session below aal2, e.g. after a reload).
 * First visit: scan a QR code into an authenticator app and confirm a code.
 * Later visits: enter the current code.
 */
export function MfaStep() {
  const [mode, setMode] = useState<Mode>({ kind: "loading" });
  const [code, setCode] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [submitting, setSubmitting] = useState(false);
  // Strict Mode runs effects twice in dev; set up only once.
  const started = useRef(false);

  useEffect(() => {
    if (started.current) return;
    started.current = true;
    const supabase = createClient();
    (async () => {
      const { data, error } = await supabase.auth.mfa.listFactors();
      if (error) {
        setMode({ kind: "error", message: error.message });
        return;
      }
      const verified = data.totp.find((f) => f.status === "verified");
      if (verified) {
        setMode({ kind: "verify", factorId: verified.id });
        return;
      }
      // Drop any half-finished setup so a fresh one can start.
      for (const f of data.all.filter((f) => f.status === "unverified")) {
        await supabase.auth.mfa.unenroll({ factorId: f.id });
      }
      const { data: enrolled, error: enrollError } = await supabase.auth.mfa.enroll({
        factorType: "totp",
        friendlyName: `VatFlow ${new Date().toISOString()}`,
        issuer: "VatFlow",
      });
      if (enrollError || !enrolled) {
        setMode({ kind: "error", message: enrollError?.message ?? "Couldn't start setup." });
        return;
      }
      setMode({
        kind: "enroll",
        factorId: enrolled.id,
        qrCode: enrolled.totp.qr_code,
        secret: enrolled.totp.secret,
      });
    })();
  }, []);

  async function handleSubmit(e: React.FormEvent) {
    e.preventDefault();
    if (mode.kind !== "enroll" && mode.kind !== "verify") return;
    setSubmitting(true);
    setError(null);
    const { error } = await createClient().auth.mfa.challengeAndVerify({
      factorId: mode.factorId,
      code: code.trim(),
    });
    if (error) {
      setError("That code didn't work. Check your authenticator app and try again.");
      setCode("");
      setSubmitting(false);
      return;
    }
    // Full load so the proxy sees the upgraded (aal2) session cookie.
    // eslint-disable-next-line @next/next/no-location-assign-relative-destination -- intentional hard reload
    window.location.assign("/");
  }

  async function handleSignOut() {
    await createClient().auth.signOut();
    // eslint-disable-next-line @next/next/no-location-assign-relative-destination -- clears cached signed-in screens
    window.location.assign("/login");
  }

  return (
    <>
      <h1 className="text-2xl font-bold">
        {mode.kind === "enroll" ? "Set up two-step sign-in" : "Enter your code"}
      </h1>
      <p className="mt-1.5 text-sm text-ink-soft">
        {mode.kind === "enroll"
          ? "Scan this QR code with an authenticator app (Google Authenticator, Microsoft Authenticator, 1Password), then enter the 6-digit code it shows."
          : "Open your authenticator app and enter the 6-digit code for VatFlow."}
      </p>

      {mode.kind === "loading" && (
        <div className="flex justify-center py-12">
          <Loader2 className="h-6 w-6 animate-spin text-ink-soft" aria-label="Loading" />
        </div>
      )}

      {mode.kind === "error" && (
        <p className="mt-6 text-sm font-medium text-critical">{mode.message}</p>
      )}

      {mode.kind === "enroll" && (
        <div className="mt-6 space-y-3">
          {/* QR code is an SVG data URL generated by Supabase */}
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img
            src={mode.qrCode}
            alt="QR code for your authenticator app"
            className="mx-auto h-44 w-44 rounded-lg bg-white p-2"
          />
          <p className="text-center text-xs text-ink-soft">
            Can&apos;t scan? Enter this key instead:
            <span className="mt-1 block break-all font-mono text-sm tracking-wider text-foreground select-all">
              {mode.secret}
            </span>
          </p>
        </div>
      )}

      {(mode.kind === "enroll" || mode.kind === "verify") && (
        <form onSubmit={handleSubmit} className="mt-6 space-y-5">
          <div className="space-y-1.5">
            <Label htmlFor="code">6-digit code</Label>
            {/* One real input (paste, autofill, screen readers) drawn as 6 boxes. */}
            <div className="group relative">
              <input
                id="code"
                inputMode="numeric"
                autoComplete="one-time-code"
                maxLength={6}
                value={code}
                onChange={(e) => setCode(e.target.value.replace(/\D/g, "").slice(0, 6))}
                autoFocus
                required
                className="absolute inset-0 h-full w-full cursor-text opacity-0"
              />
              <div className="pointer-events-none grid grid-cols-6 gap-2" aria-hidden="true">
                {Array.from({ length: 6 }, (_, i) => (
                  <div
                    key={i}
                    className={`flex h-12 items-center justify-center rounded-lg border bg-surface font-mono text-xl font-semibold ${
                      i === Math.min(code.length, 5)
                        ? "border-line group-focus-within:border-brand group-focus-within:ring-2 group-focus-within:ring-brand/30"
                        : "border-line"
                    }`}
                  >
                    {code[i] ?? ""}
                  </div>
                ))}
              </div>
            </div>
          </div>

          <div className="min-h-5 text-sm" role="status" aria-live="polite">
            {error && <p className="font-medium text-critical">{error}</p>}
          </div>

          <Button
            type="submit"
            disabled={submitting || code.length !== 6}
            className="h-10 w-full"
          >
            {submitting && <Loader2 className="h-4 w-4 animate-spin" />}
            {submitting ? "Verifying…" : mode.kind === "enroll" ? "Turn on and continue" : "Verify"}
          </Button>
        </form>
      )}

      <p className="mt-6 text-center text-sm text-ink-soft">
        {mode.kind === "verify" && "Lost your phone? Ask your shop admin to reset your two-step sign-in. "}
        <button
          type="button"
          onClick={handleSignOut}
          className="font-semibold text-brand hover:underline"
        >
          Sign out
        </button>
      </p>
    </>
  );
}
